/**
 * 管理画面の「保存」操作の結果を、画面と読み上げに出す文言へ写す (#973)。
 *
 * ## なぜ分けるか
 *
 * 設定系の `save` は例外なく `try { … } finally { setBusy(false) }` で、**`catch` が
 * 無かった**。`fetch` が reject する経路（オフライン・DNS 失敗・API 停止）では押しても
 * ボタンが戻るだけで、画面にも読み上げにも何も出ない。運用者は「保存できたのか、
 * 押せていないのか」を区別できず、同じ操作を繰り返す。
 *
 * 🔴 **`catch` で既定の `failure()` を呼べばよい、ではない。** 既定文言は
 * 「保存に失敗しました。」＝**サーバが拒否した**ときの言い方であり、届いていない場合に
 * 使うと嘘になる（サーバは要求を見てすらいない）。原因の異なる失敗は別の文言にする。
 *
 * 🔴 **「保存されていません」とも言えない。** reject は「応答を受け取れなかった」だけで、
 * 要求がサーバへ届いて適用された直後に接続が切れた可能性が残る。断定すると
 * `.claude/rules/opus5-autonomous-loop.md`「果たせない約束をしない」に反する ――
 * 運用者へ渡すべきは「分からないので確かめてほしい」という**次の行動**である。
 *
 * 純関数にしてあるのは、この写像だけを unit で縛れるようにするため
 * （このリポジトリの component テストは静的レンダリングで、送信の相互作用は e2e 側にある）。
 */

/** 保存操作の失敗。**原因が違えば運用者にできることも違う**ので、同じ値にしない。 */
export type SaveFailure =
  /** サーバが答えを返し、それが「保存しない」だった（4xx/5xx）。押し直しても同じ。 */
  | 'rejected'
  /** 応答を受け取れなかった。**保存されたかどうかは分かっていない**。 */
  | 'unreachable';

/**
 * 画面と読み上げに出す文言。
 *
 * `rejected` は `useSaveFeedback` の既定文言と同一にしてある（既存の e2e / 画面表示を
 * 変えないため）。**ここが正本**で、フックの既定はこれを引く。
 */
export function saveFailureMessage(failure: SaveFailure): string {
  switch (failure) {
    case 'rejected':
      return '保存に失敗しました。';
    case 'unreachable':
      return 'サーバーに接続できませんでした。保存できたか分かりません。通信状態を確かめてから、画面を再読み込みして確かめてください。';
  }
}
