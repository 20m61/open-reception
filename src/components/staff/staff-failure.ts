/**
 * 担当者画面の失敗を、画面に出す文言へ写す (#1123)。
 *
 * ## なぜ分けるか
 *
 * `StaffCallView` / `StaffResponseActions` は非 ok を一括で `error` にし、
 * 「**リンクの有効期限切れ**、または…の可能性があります」と出していた。#1021 で
 * `CALL_ANSWER_SECRET` が failClosed になり担当者向け API が **5xx を返しうる**ように
 * なったので、**サーバの設定漏れでも「リンク切れ」と伝わる**状態になった。
 *
 * 🔴 これは #973 が admin ログインで塞ぎ、#1021 が `loginFailureForStatus` で塞ぎ直したのと
 * **同型・同一原因**（failClosed が新しい応答クラスを作ったこと）である。同じ形で解く。
 *
 * 縛る不変条件は 1 つ:
 *
 * > 「リンクの有効期限切れ」と出してよいのは、**サーバが要求を検査したうえで断ったとき
 * > （アプリが返した 4xx）だけ**である。5xx はサーバ側の問題で、リンクは無関係。
 *
 * 🔴 **縛れたのは片側だけである。** 「5xx ならサーバ側の問題」は成立するが、その裏
 * （「4xx なら要求が判定された」）は**成立していない** —— `src/proxy.ts` の origin-verify
 * `mismatch`（配備の全断なのに 403）に加え、**この increment が編集した route 自身**が
 * 設定不備を 4xx で返している: `answer` はテナントに Vonage 資格情報が無いと **409**
 * `{error:'unavailable'}`（未設定が既定状態）、`respond` は `409 action_disabled` 等。
 * これらは今も `rejected`＝「リンクの有効期限切れ」と表示される。
 * **「もう塞いだ」と読ませない。** 揃えるのは #1127 の射程（レビュー 6 周目の実測）。
 *
 * 🔴 **文言に env 名・鍵名を出さない。** 担当者リンクは通知で配られ、**未認証で開かれる**
 * （リンクを持っている人、でしかない）。設定の内訳は攻撃者への情報になる
 * （`rules/pii-secret-minimization.md`）。原因の特定はサーバログ側の仕事。
 */
import { isServerSideFailure } from '@/domain/util/http-failure';

/** 担当者操作の失敗。**原因が違えば担当者にできることも違う**ので、同じ値にしない。 */
export type StaffFailure =
  /** サーバが**要求を検査したうえで**断った（4xx）。リンク切れ・応答済み・受付終了など。 */
  | 'rejected'
  /**
   * サーバ側の問題で処理できなかった（5xx）。
   *
   * 🔴 #1123 で `/api/staff/calls/*` は鍵未設定のとき **503** を返すようになった。
   * 担当者にできることは「リンクを取り直す」ではなく「時間をおく・運用者へ知らせる」。
   */
  | 'unavailable'
  /**
   * 通話を確立できなかった。**成否は分かっていない**。
   *
   * 2 つの経路が入る:
   * - `fetch` が reject（オフライン・DNS 失敗）—— サーバは要求を見ていない
   * - 🔴 Vonage の `onError` —— **answer API は 200 を返し終えており、サーバは受付を
   *   `connected` に確定済み**。つまり「受付は応答済み、通話には誰も居ない」状態になる。
   *
   * 🔴 **今日この経路は「常に」発火する。** `src/lib/security/csp.ts` の
   *   `script-src 'self' 'nonce-…'` は Vonage SDK の CDN を許可していないので、
   *   ブラウザが読み込み自体を拒否する（#1123 レビュー 6 周目の実測）。**配信側の設定**が
   *   原因であって、見ている人の回線ではない。
   *
   * 🔴 **文言から回線の断定を外した (#1132 増分 1)。** 以前は「通信状態を確かめて」と
   *   書いており、`onError` 側では**嘘**だった（answer API は 200 を返し終えている）。
   *   ただし**2 経路を 1 つの値のまま**にしてある —— 分けるべき時期は CSP が開いた後
   *   （`onError` が「本当にメディアを確立できなかった」を意味するようになってから）で、
   *   今分けると**今日は存在しない区別**を機構として固定することになる。
   *   復帰導線そのものは **#1129**、CSP の実配線は **#1132 増分 2**。
   *
   * 🔴 **今日この画面で有効な次の一手を指す。** 同じ画面には `StaffResponseActions`
   *   （fallback-first・#99）が併設されており、CSP 由来の失敗なら来訪者へ返答できる。
   *   🔴 **ただし「常に」ではない (#1137)。** サイト設定で応答種別を全部無効化していると
   *   ボタンは 0 個になるので、**指すかどうかは `responsesShown` で決める**。
   *   今日は `onError` が決定論的に発火するので、「時間をおいて開き直す」だけを案内すると
   *   担当者が再読込を繰り返す間、**来訪者は「つながった」状態のまま待たされる**
   *   （answer API は 200 を返し終えている）。
   *
   * 🔴 **ただし「返答できます」とは断定しない（レビュー 4 周目）。** もう一方の経路
   *   （`fetch` の reject＝回線断）では `StaffResponseActions` も**同じ `fetch` を撃つので
   *   必ず失敗する**。断定すると、このモジュール自身の基準
   *   「**対を揃えることが目的ではなく、それぞれの経路で真であること**」に違反する。
   *   経路を分けるのは #1129 / 増分 2。
   *
   * 🔴 **その代償を書いておく（レビュー 6 周目）。** 回線断の経路では
   *   `StaffResponseActions` も同じ `fetch` を撃って必ず失敗するので、
   *   担当者は「試せます」に従って 1 手押してから、応答側の文言
   *   （`staffResponseFailureMessage('unreachable')` の「通信状態を確かめて」）へ到達する。
   *   **旧文言はこの経路では 1 手早く actionable だった** —— 2 経路を 1 つの値で賄う限り
   *   どちらかが遠くなる。今日は `onError` 側が 100% 発火するのでそちらを近くした。
   */
  | 'unreachable';

/**
 * HTTP 応答の状態コードを失敗の種類へ写す。
 *
 * 状態コードを見ずに「非 ok はすべて `rejected`」にすると、#973 が塞いだ嘘を
 * **別の入口（5xx）から踏み直す**ことになる —— #1021 の admin 側で実際に踏んだ。
 */
export function staffFailureForStatus(status: number): StaffFailure {
  return isServerSideFailure(status) ? 'unavailable' : 'rejected';
}

/**
 * 文言を決めるのに必要な、**いま画面に出ているもの**。
 *
 * 🔴 **既定値を持たせない (#1137)。** 省略できるようにすると、その既定は
 * 「応答導線は在る」＝**嘘になりうる側**へ倒れる。このモジュールが #1123 で
 * `SubmitState` に対して採った形（「error は必ず原因を伴う」）と同じ理由で、
 * **呼び出し側に必ず書かせる**。
 */
export type StaffCallFailureContext = {
  /**
   * **いま画面に応答ボタンが出ているか。**
   *
   * サイト設定で全部無効化されていると `StaffResponseActions` はボタンを 1 つも出さない。
   * そのとき「下の応答からの返答も試せます」は**空の領域を指す** —— 担当者は画面下を
   * 探しに行き、その間**来訪者は呼び出しが成立したまま待つ**（#1137）。
   *
   * 🔴 **「押せば必ず通る」ではない（レビュー 1 周目 MAJOR 1）。** 取得前・取得失敗時は
   * ドメイン既定（全 `defaultEnabled`）へ倒れるので、この値は**画面の描画と一致する**が
   * サイト設定の事実とは限らない。`fetch` reject 経路（回線断）では GET も同時に落ちるので、
   * **ほぼ必ずその世界に入る**。
   *
   * 縛れているのは 1 つだけである:
   *
   * > **この値が真 ⟺ 画面に応答ボタンが出ている。**
   *
   * 押した先が `409 action_disabled` で断られたときに「リンクの有効期限切れ」と表示される面は
   * **この increment では塞いでいない** —— 上の doc が書いているとおり **#1127 の射程**である
   * （`staffFailureForStatus` が status だけを見る設計に触れるため）。
   */
  responsesShown: boolean;
};

/** 通話への参加に失敗したときの文言。 */
export function staffCallFailureMessage(
  failure: StaffFailure,
  context: StaffCallFailureContext,
): string {
  switch (failure) {
    case 'rejected':
      return '通話に接続できませんでした。リンクの有効期限切れ、または別の端末で応答済みの可能性があります。';
    case 'unavailable':
      return 'サーバー側の問題で通話に接続できませんでした。時間をおいても直らない場合は、管理者へ知らせてください。';
    case 'unreachable': {
      // 🔴 **回線を断定しない (#1132)。** ここに入る経路は 2 つあり、Vonage の `onError`
      // 側では **answer API が 200 を返し終えている**ので回線は容疑者ではない。
      // しかも今日その側は CSP により**常に**発火する。先例は `save-outcome.ts` の
      // `unreadable`（「通信状態を確かめてください」は誤った方向へ調べに行かせる）。
      //
      // 🔴 **指す先が在るときだけ指す (#1137)。** 応答種別を全部無効化したサイトでは
      //    `StaffResponseActions` にボタンが 1 つも無い。指せないときは 1 文を落とし、
      //    **残りの次の一手（開き直す／管理者へ知らせる）は残す** —— 全部を曖昧にしない。
      const fallback = context.responsesShown ? '下の応答からの返答も試せます。' : '';
      return `通話に接続できませんでした。原因は特定できていません。${fallback}時間をおいて開き直すか、管理者へ知らせてください。`;
    }
  }
}

/** 応答種別の送信に失敗したときの文言。 */
export function staffResponseFailureMessage(failure: StaffFailure): string {
  switch (failure) {
    case 'rejected':
      return '応答を送れませんでした。リンクの有効期限切れ、または受付が終了している可能性があります。';
    case 'unavailable':
      return 'サーバー側の問題で応答を送れませんでした。時間をおいても直らない場合は、管理者へ知らせてください。';
    case 'unreachable':
      return 'サーバーに接続できませんでした。応答が届いたか分かりません。通信状態を確かめてから、もう一度お試しください。';
  }
}
