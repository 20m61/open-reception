/**
 * 「読み取りが今どうなっているか」の 3 状態 (#870 増分 04 / #1004 増分 2 で共有化)。
 *
 * ## なぜ型を分けるか
 *
 * 多くの画面は取得結果を `T | null` の 1 変数で持ち、`null` を「読み込み中」と読んでいた。
 * **`null` は「まだ」と「だめだった」の両方を表せてしまう**ので、失敗が「読み込み中…」に
 * 化ける。利用者は終わらない待ちに入り、何が起きたかも再試行の手段も画面に無い。
 *
 * 3 状態を明示的に持てば、その取り違えは**書けなくなる**。
 *
 * ## なぜ `src/domain/` にあるか（#1004 増分 2）
 *
 * 元は `src/components/admin/read-state.ts` にあり、管理画面 15 箇所が使っていた。
 * 🔴 **来訪者導線が同じ問題を手で導き直し、規則を 2 つとも外した**（独立レビュー 4 周目）——
 * 「まだ」を「0 件」と言い、再取得の失敗で**既に載っている一覧を消して**いた。
 * 正解がリポジトリに在るのに使わなかったのが原因なので、**両方から使える場所へ移す**。
 * `admin/read-state.ts` は互換のため再輸出だけを残す（15 箇所の import を変えない）。
 */

/** 読み取りの状態。**「まだ」と「だめだった」を混ぜない。** */
export type ReadState = 'loading' | 'failed' | 'loaded';

export type ReadStateInput = {
  /** 現在の対象のデータが載っているか。 */
  readonly loaded: boolean;
  /** 直近の読み取りが失敗したか（HTTP エラー・オフライン・形が違う 200 の全部）。 */
  readonly failed: boolean;
};

/**
 * 読み取りの状態を決める。
 *
 * 🔴 **載っていることを優先する。** 再取得が失敗しても、既に載っているデータは消さない
 * （消すと「更新に失敗したら画面ごと空になる」という、**失敗が状況を悪化させる**形になる）。
 * 失敗は消す理由ではなく**添える理由**である ―― 呼び出し側は `loaded` のまま
 * `failed` を併記して「表示は前回時点」と言う。
 */
export function resolveReadState(input: ReadStateInput): ReadState {
  if (input.loaded) return 'loaded';
  return input.failed ? 'failed' : 'loading';
}
