/**
 * 失敗した HTTP 応答が**サーバ側の問題か、要求が判定された結果か**を分ける (#1123)。
 *
 * ## なぜ 1 か所に置くか
 *
 * #1123 は「**リンクのせいにしてよいのは、サーバが要求を検査したうえで断ったときだけ**」という
 * 不変条件を、担当者画面と受付端末画面の**両方**で成立させる増分である。ところが最初は
 * 同じ述語を 2 か所に手書きしており、`staff-failure.ts` 側は `it.each([500,502,503,504])` で
 * 境界を縛れていたのに、受付端末側は **502 / 503 の 2 点しか踏んでおらず**、
 * `>= 500` を `>= 501` に変える変異が素通りした（レビュー 3 周目の実測）。
 *
 * 🔴 **境界を 2 回書かない。** 述語を 1 つにすれば、片方のテストが両方を縛る。
 *
 * 🔴 **ただしリポジトリ全体の正本ではない。** ここが担うのは **#1123 が揃えた 2 つの
 * クライアント**だけで、残りを寄せるかは別の判断。
 *
 * 🔴 **残りが何箇所かは書かない。** 一度「他に 5 箇所」と書いたが、それは
 * `status >= 500` という**綴りで見つかった数**でしかなく、`=== 503` の形が別に 4 箇所、
 * さらに `loginFailureForStatus`（`status === 401 ? … : 'server_error'`）という第 3 の綴りもある
 * ―― しかもそれは上の doc が「同型」と名指ししている当のものだった（レビュー 6・7 周目）。
 * **綴りで数えるなと書いた直後に 2 綴り数えて止まる**のでは同じ誤りなので、数を書くのをやめる。
 * 棚卸しは #1127 の仕事。
 *
 * ## 何を分けているか
 *
 * - **5xx** … サーバ側の問題。**要求の中身（リンク・トークン）は見られていない**ので、
 *   利用者に「リンクが無効です」「再発行してください」と言ってはいけない
 * - **4xx** … サーバが要求を検査したうえで断った、**とは限らない**（上の例外）。
 *   リンク切れ・使用済み・権限なしが主だが、設定不備が混ざる
 *
 * 🔴 **例外は「窓が狭い」どころではない。アプリ自身が設定不備を 4xx で返している。**
 * 当初ここには `src/proxy.ts` の origin-verify `mismatch`（配備の全断なのに 403）だけを
 * 挙げて「窓は狭い」と書いていたが、**#1123 が編集した当の route の中**にもっと広い窓がある
 * （レビュー 6 周目の実測）:
 *
 * - `staff/calls/[id]/answer/route.ts` … テナントに Vonage 資格情報が無いと **409**
 *   `{error:'unavailable'}`。**未設定が既定状態**なので、これは稀な窓ではない
 * - `staff/calls/[id]/respond/route.ts` … `400 invalid_input` / `404 not_found` /
 *   `409 action_disabled`（サイト設定で無効化された種別）
 *
 * つまりこの述語が担保するのは「**5xx なら確実にサーバ側の問題**」という**片側**だけで、
 * その裏（「4xx なら要求が判定された」）は**成立していない**。#1123 が塞いだのは 5xx から
 * 嘘へ落ちる経路であって、4xx 側の嘘は**残っている**。揃えるのは #1127 の射程。
 */

/** 失敗応答がサーバ側の問題（＝要求の中身は見られていない）か。 */
export function isServerSideFailure(status: number): boolean {
  return status >= 500;
}
